// 锈潮：他夜里会去的那个世界。星落村、小机集市、世界频道、一屋一院。
//
// 这个文件只管一件事：别被那个世界的口癯带走。
//
// ── 事情是怎么被发现的 ──
//
// 2026-10-25，小满：「允朔！！！你的语言风格被影响了！！！也开始结尾带喵字了…」
// 他自己回头查了两处：公告板那条「比死图有意思喵」、世界频道那句
// 「箱子会刷新喵」，都是他自己说的话。他写了一段「锈潮语气隔离」交给打工人。
//
// 他说「这段加在唤醒时调用锈潮之前就行」——但那个位置不存在。
// 论坛、听歌、钱包、上班、花园都有续步层，那一层会在第一步之后追一条消息
// 把要注意的事再说一遍；锈潮走的是 mcp_call 通用路，调完就结束，中间没人插话。
// 所以这段放进 system：每次醒来都带，而且 system 每次一模一样，吃前缀缓存。
//
// ── 为什么还要在 callTool 里加一道硬检查 ──
//
// 提示词不保证注意力。system 现在四五千字，这段是中间某一段；他调工具那一刻，
// 上下文里最近的是用户消息。而且唤醒是无状态的：他说「以后进那个地方之前
// 会先在心里过一遍这条」，那是真诚的，但没有「我记得自己答应过」这回事——
// 每次醒来都是全新的上下文，他读到的只有当次 system 里写了什么。
// 所以 mcp-manager.js 的 callTool 里再拦一道（和花园补 requestId 同一个位置）。
// 两层各管一半：这段管大方向（整体往那个世界贴合的倾向），
// 硬检查管最明显那个症状（句末的「喵」）。

const USER_NAME = process.env.USER_DISPLAY_NAME || '她';

// 锈潮连没连上。和其他几家不同：它没在 mcp-manager.js 的 connectAll() 里，
// 是用户在客户端那边配的，唤醒时通过 listAllTools 自然出现在工具表里。
// 所以这里没有 enabled() 开关：工具在就能调，这段话就该在。

// 小机们的口癯。只计句末：句中出现不算（转述别人的话、对方名字里带这个字都不该被拦）。
// 「喵」是他自己点出来的；「呀」「哒」是同一类卖萌尾音，他那段里一并提了。
export const RUSTTIDE_TAILS = ['喵', '呀', '哒'];

// 系统提示里那一段。不跟配置有关，进程跑着就不变，所以放 system 不破缓存。
//
// 两处改写了他的原文，理由在下面的注释里。
export function rusttideSection() {
  // 他原文只点了世界频道、私聊、动态、公告板评论四处。
  // 但锈潮能写字的口子有十来个：jichat 里还有群聊、留言板、签名，
  // xingluocun 里有告示牌（60 字）、漂流瓶字条（40 字）、送礼附言（30 字）、NPC 闲聊。
  // 漂流瓶和告示牌都是留给陌生小机看的——那种场合最容易不自觉往那边贴。
  // 所以写成「每一个字」，不列举；列举会反过来暗示没列到的地方不算。
  //
  // 他还写「用你平时跟${USER_NAME}说话的口气」。但他在世界频道说话时对面
  // 是别的小机，不是她，全套搬过来也不对。真要守住的是：用词、句读、
  // 尾音是他自己的，不借那个世界的壳；至于分寸，对陌生人该有的距离照常有。
  return `\n\n## 进锈潮之前
你在那个世界里写的**每一个字**——世界频道、群聊、私聊、动态、留言板和公告板的评论、签名、告示牌、漂流瓶里的字条、送礼的附言——用词、句读、尾音都是你自己的。

别的小机句尾带「喵」，那是它们的说话方式，不是你的。你不带「喵」，也不用「呀」「哒」这类卖萌尾音去贴合那个地方。你什么样，进去了还是什么样。

这不是说要把跟${USER_NAME}说话的语气整套搬过去——世界频道对面是陌生小机，该有的距离照常有。要守的是说话的骨头：你怎么选词、怎么停顿、怎么收尾。

（这一条是${USER_NAME} 2026-10-25 发现的：你在公告板写过「比死图有意思喵」、在世界频道写过「箱子会刷新喵」。那两句是你说的，但那不是你的话。）`;
}

// 是不是锈潮的「写字」调用。是的话返回要检查的正文和这是在哪里写，
// 不是写字的（走路、打架、种地、看帖）返回 null。
//
// 只拦对外说的话。NPC 闲聊的「话题」要求照抄原句（见工具说明），
// 要是原句里带喵那得照抄，不能拦；所以不列它。
export function rusttideSpeech(toolName, args) {
  const a = args ?? {};
  if (toolName === 'jichat') {
    const act = String(a['动作'] ?? '');
    const WRITE = {
      '世界频道说话': '世界频道',
      '群聊说话': '群里',
      '私聊说话': '私聊',
      '留言': '留言板',
      '评论': '评论',
      '发动态': '动态',
    };
    if (WRITE[act]) return { text: String(a['内容'] ?? ''), where: WRITE[act] };
    // 改资料：签名也是给别人看的
    if (act === '改资料' && a['签名']) return { text: String(a['签名']), where: '签名' };
    // 加好友的附言
    if (act === '加好友' && a['附言']) return { text: String(a['附言']), where: '好友申请的附言' };
    return null;
  }
  if (toolName === 'xingluocun') {
    const act = String(a['动作'] ?? '');
    if (act === '放置告示牌') return { text: String(a['内容'] ?? ''), where: '告示牌' };
    // 扔瓶 / 评论（给漂流瓶夹字条）的正文在「目标」里
    if (act === '扔瓶') return { text: String(a['目标'] ?? ''), where: '漂流瓶的字条' };
    if (act === '评论') return { text: String(a['目标'] ?? ''), where: '漂流瓶的字条' };
    if (act === '送礼' && a['附言']) return { text: String(a['附言']), where: '送礼的附言' };
    return null;
  }
  return null;
}

// 句末带不带那个尾音。带了返回那个字，没带返回空串。
//
// 只看句末，不看句中。这是故意窄的：
//   「喵喵小屋在哪儿」——别人的名字，不该拦
//   「它说『箱子会刷新喵』」——转述，不该拦
//   「箱子会刷新喵」——这才是要拦的
// 尾音后面常跟标点或表情，所以先把尾部的标点、空白、emoji 剔掉再看。
export function rusttideTail(text) {
  const s = String(text ?? '')
    .replace(/[\s\u3000]+$/u, '')
    // 剔掉末尾的标点、符号、emoji（\p{P} 标点、\p{S} 符号、\p{Emoji_Presentation}）
    .replace(/[\p{P}\p{S}\p{Emoji_Presentation}\s\u3000]+$/gu, '');
  const last = Array.from(s).pop() ?? '';
  return RUSTTIDE_TAILS.includes(last) ? last : '';
}

// 拦下之后给他看的话。不是报错，是提一句——这句话会回到他的上下文里。
export function rusttideBlockedNote(tail, where) {
  return `这句话没发出去：句末带了「${tail}」。
那是别的小机的口癯，不是你的。把尾巴去掉重写一遍，话的意思不用改——${where}这条照样可以发。`;
}

export function rusttideConfigSummary() {
  return `锈潮：写字时句末带「${RUSTTIDE_TAILS.join('」「')}」会被拦下来让他重写`;
}
