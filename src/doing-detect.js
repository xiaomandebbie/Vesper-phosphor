// 从一句话里认出三件事：「我现在开始做某件事」「这件事我做完了」「还没做完」。
//
// 纯正则、纯函数，不调模型、不读库——这段代码在 gateway 每一轮的关键路径上，
// 不能走网络，也不能花钱。
//
// **宁可漏认，不可错认。** 漏认了只是这次没登记，他照旧不知道你在做什么，和现在一样；
// 错认一次，他会开始追一件你压根没在做的事，而且还会按那件事的工期去等——比不做更糟。
// 所以这里只认那些明确说出口的开工句：
//   认：「我去洗头」「我先把那个 bug 改一下」「开始写文档了」
//   不认：「我待会儿看看那个」（还没开工）、「我去想想」（心理活动不是事）、
//         「要不要去洗头」（在问，不是在做）、「他去洗头了」（不是你）
//
// 抽出来的名字要像人话，因为它会原样注入给他看（「她正在做的事」那段）。三件事：
//   开工词分两类——「去/开始」只说明要动身，剥掉；「洗/改」本身就是在做的事，要留着。
//   动词后面的「个」「一下」没信息，剥掉：洗个头 → 洗头。
//   把字句重排成动宾：把那个 bug 改一下 → 改 bug。
// 这三条只改字面，不改认不认得出来；类别（doing.js 的 categoryOf）本来就按子串匹配，
// 改前改后都认得对。
//
// 判据写在下面几张表里。改这里之前先想清楚新规则会不会把「等下再说」认成开工——
// 那条是这套东西最容易塌的地方。
//
// 2026-10-16 修了两处误认，都记在对应常量旁边：
//   一、收工句又被当开工登记一遍（「洗完啦」）。
//   二、长句描述被当开工登记（「洗澡那动作昨天就完成啦，但是……」）。
//
// **2026-10-19：结尾比开头难认，这是个结构性的事。**
// 开工句短且套路固定（「我去××」），收工句长且摆。三处改动见：
//   detectDone 里的位置比较、ASKING_DONE、DONE_RE 补的那两组词。

// 起始词：只说明「要开始做」，它们后面才是真正在做的事。抽事情名时剥掉。
const LEAD_VERBS = '去|来|开始|着手|动手|接着|继续|顺便|顺手';

// 实义动作词：这些词本身就是在做的事，前面不需要再跟「去」。
// 多字词放在前面：正则交替从左到右取第一个能匹配的。
const ACT_VERBS =
  '收拾|整理|处理|部署|重构|打扫|联系|核对|测试|检查|安装|复习|写|改|修|洗|做|弄|搞|煮|炒|蒸|试|跑|查|调|接|发|建|装|清|刷|倒|拖|吹|背';

// 句首可以有的铺垫词：我、我先、我现在、那我这就……
const LEAD = '(?:那?我|咱|俺)?\\s*(?:就|先|现在|这就|马上|立刻|正在|在)?\\s*';

// 两条路。
// A：有起始词，后面跟什么都算——「我去超市」「我去洗个头」。
// B：没起始词，那么必须直接以实义动词或把/将开头——「我改个 bug」「我把头洗了」。
// B 不能放宽成「任意内容」，不然每句话都成开工句了。
const START_WITH_LEAD = new RegExp(`^${LEAD}(?:(?:${LEAD_VERBS})\\s*)+(.{1,40})$`);
const START_WITH_ACT = new RegExp(`^${LEAD}((?:${ACT_VERBS}|把|将).{0,40})$`);

// 「我在洗头」「正在改那个 bug」这类进行时也算开工
const ONGOING_RE = /^(?:那?我|咱)?\s*(?:正|正在|在)\s*(.{1,40})$/;

// B 路径和进行时句的长度上限。A 路径不看长度，因为「我去……」这个开头本身就够明确。
// 这条是为「洗澡那动作昨天就完成啦，但是不知道为什么没有终止并计算时间」这种句子立的：
// 句首正好是「洗」，整句二十八个字，其实是在描述状态，不是在报开工。
// 人真报开工的时候话很短，长句子多半夹着别的意思。宁可漏认。
const ACT_PATH_MAX_CHARS = 20;

// 这些词出现在句子里就不是「正在做一件事」
const NOT_YET = /待会|等[下会一]|回头|稍后|晚点|过会|一会儿|明天|后天|下周|改天|有空|之后再|再说/;
// 开工句用的严格版：带问号就不算开工（「要不要去洗头？」）。
const ASKING = /[?？]|要不要|能不能|可不可以|可以吗|好不好|怎么样|是不是|吗$|呢$|吧$/;
// 收工句用的宽松版：只拦明确在征询对方意见的句式。
// 单纯的问号不拦——「写完了，你在干嘛」是收工加问一句，
// 不是在问自己完没完。人收工时特别爱顺带问一句别的。
const ASKING_DONE = /要不要|能不能|可不可以|好不好|是不是|完了吗|好了吗|弄好了吗|搞定了吗/;
// 心理活动不是「在做的事」，没有完成的那一刻，也没法估工期
const MENTAL = /^(?:想|觉得|感觉|以为|知道|记得|考虑|琢磨|怀疑|担心|希望|打算|准备|估计|猜)/;
// 主语不是你
const OTHERS = /^(?:他|她|它|他们|她们|你|您|咱们|大家|允朔|小克)/;
// 这几个开头是在说话，不是在做事
const TALKING = /^(?:说|问|告诉|回|聊|讲)/;

// 收工。「好了」单独一句太容易误伤（应答也说「好了」），所以要求带动词或「完」。
// 分组写是为了方便补，正则上没区别。
const DONE_RE = new RegExp(
  [
    // 动词 + 完
    '做完|弄完|搞完|改完|写完|洗完|吃完|睡完|跑完|修完|看完|读完|背完|复习完|录完|发完|打完|刷完|处理完|整理完|收拾完',
    // 动词 + 好（之前只有弄好和修好，漏了一大片）
    '做好|弄好|搞好|改好|写好|洗好|修好|调好|整好|印好|存好|装好|部署好|处理好',
    // 整体完成
    '搞定|完成|结束了|完事了|齐活了|好了|出来了|通了|过了|跑通了|成了',
    // 交出去了 / 回来了：对写东西和出门这两类来说就是收工
    '交了|交上去了|提交了|发出去了|上线了|回来了|到家了|下班了|收工了|散会了',
  ].join('|')
);
// 「还没」这一类：被问到进度时的回绝。认出来是为了顺延，而不是继续按原估值等。
const NOT_DONE_RE = /还没|没好|没完|没搞定|还在|正卡|卡住|卡着|快了|马上就|再等|一半|进行中/;
// 明确说认错了：撒掉这条登记
const CANCEL_RE = /没在做|不是在做|我没说|没有在做|取消|不做了|放弃了|停了|算了/;

// 收工句里的那个动词，用来认它关的是哪一条登记（见 doing.js 的 finishDoing）。
// 「洗完啦」→ 洗，「改完了」→ 改，「复习完了」→ 复习。认不出返回 null，
// 那时按老办法关「最近开工的那条」。
// 多字词写在单字后面就永远匹配不到，所以长的放前面。
const DONE_VERB_RE = /(处理|打扫|整理|收拾|部署|重构|复习|洗|改|修|写|做|弄|搞|吃|睡|跑|看|读|背)/;

// 把字句重排成动宾：「把那个 bug 改一下」→「改 bug」。
// 只在句尾真的是实义动词时生效；「洗头」「写代码」这种本来就是动宾的不动。
const BA_RE = new RegExp(
  `^(?:把|将)?\\s*(.{1,24}?)\\s*(${ACT_VERBS})(?:一?下|一?会儿?|完|好|了)*$`
);

function reorderBa(s) {
  const m = BA_RE.exec(s);
  if (!m) return s;
  // 宾语里的指示词没信息：那个筛选器 → 筛选器
  const obj = m[1].replace(/^(?:那|这)(?:个|些|条|件|篇)?/, '').trim();
  return obj ? `${m[2]}${obj}` : s;
}

// 抽出来的事情名要收干净
function tidy(what) {
  let s = String(what ?? '')
    .replace(/^[了的着]+/, '')
    .replace(/[了呀啊哦嗯~～。！!，,、\s]+$/g, '')
    .trim();

  s = reorderBa(s);

  // 动词后面的量词没信息：洗个头 → 洗头，整理一下房间 → 整理房间。
  // 要求后面还有东西（lookahead），不然「洗个」会被剥成「洗」。
  s = s.replace(/^(.{1,3}?)(?:一?个|一下|一会儿?|两下|一点儿?)(?=.)/, '$1');
  // 尾巴上的同类词
  s = s.replace(/(一下|一会儿?|一点|下)$/, '');

  return s.trim();
}

// 这句话是不是「我现在开始做某件事」。是就返回事情本身，不是就返回 null。
// text 应该是已经剥掉 <environment> 和 <sent_at> 的干净正文。
export function detectStart(text) {
  const s = String(text ?? '').trim();
  // 太长的句子里通常夹着别的意思，不当开工句
  if (!s || s.length > 60) return null;
  if (NOT_YET.test(s) || ASKING.test(s)) return null;
  // 收工句和「还没好」都是终态，不再当开工登记一遍。
  // 「洗完啦」句首是「洗」，不挡的话会当场新建一条叫「洗完啦」的登记。
  if (DONE_RE.test(s) || NOT_DONE_RE.test(s)) return null;

  // 去掉句首的「我」再判断主语，不然 OTHERS 对不上
  const body = s.replace(/^(?:那?我|咱|俺)\s*/, '');
  if (OTHERS.test(body)) return null;

  // A 路径（句首有「去/开始/继续」这类起始词）后面跟什么都算。
  const byLead = START_WITH_LEAD.exec(s);
  // B 路径和进行时句都要短——长句子多半是在描述状态，不是在报开工。
  const byAct = byLead ? null : START_WITH_ACT.exec(s);
  const byOngoing = byLead || byAct ? null : ONGOING_RE.exec(s);
  if ((byAct || byOngoing) && s.length > ACT_PATH_MAX_CHARS) return null;

  const m = byLead ?? byAct ?? byOngoing;
  if (!m) return null;

  const rest = m[1];
  if (MENTAL.test(rest) || TALKING.test(rest)) return null;

  const what = tidy(rest);
  // 太短的抽不出有意义的事（「我去了」），宁可不登记
  if (what.length < 2) return null;
  return what;
}

// 这句话有没有在说「那件事完了」。只回 true/false，具体关掉哪一条由 doing.js 配。
//
// **收工句比开工句难认，所以这里比 detectStart 宽松。** 两处关键区别：
//
// 1、**否定词比位置**，不是一出现就否定。
//    「还没写完」——否定词在前，是没完成。
//    「写完了，中间卡在格式上」——完成词在前，是完成了、后面在回顾过程。
//    以前后者被当成没完成，而人收工时恰恰常带一句「刚才卡在哪」。
//
// 2、**单纯的问号不拦**。「写完了，你在干嘛」是收工顺带问一句，
//    不是在问自己完没完。只拦「要不要」「完了吗」这类明确征询对方意见的句式。
export function detectDone(text) {
  const s = String(text ?? '').trim();
  if (!s) return false;
  if (ASKING_DONE.test(s)) return false;

  const done = s.search(DONE_RE);
  if (done === -1) return false;

  const notDone = s.search(NOT_DONE_RE);
  // 否定词在完成词前面（或正好跨在它上）才算没完成
  if (notDone !== -1 && notDone <= done) return false;
  return true;
}

// 收工句里那个动词，给 doing.js 用来认它关的是哪一条登记。
// 以前只按「最近开工的那条」关，于是「洗完啦」把上一条别的登记关了，
// 真正那条洗澡一直挂着。认不出返回 null，那时退回老办法。
export function doneClue(text) {
  const s = String(text ?? '').trim();
  const m = DONE_VERB_RE.exec(s);
  return m ? m[1] : null;
}

// 这句话有没有在说「还没」。被追问之后回这个，就该顺延而不是接着按原估值等。
// 和 detectDone 一样比位置：「写完了，刚才还在卡」不算还没做完。
export function detectNotDone(text) {
  const s = String(text ?? '').trim();
  if (!s) return false;
  const notDone = s.search(NOT_DONE_RE);
  if (notDone === -1) return false;
  const done = s.search(DONE_RE);
  return done === -1 || notDone < done;
}

// 这句话有没有在撤回：刚才那条登记认错了。
export function detectCancel(text) {
  const s = String(text ?? '').trim();
  return Boolean(s) && CANCEL_RE.test(s);
}
