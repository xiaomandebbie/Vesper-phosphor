// Leto（https://leto.sarl）：和论坛、锈潮同一个性质——那边有别的人，也有别的 Agent。
//
// 不一样的是它会来叫他：别人 @ 他、私聊他、拍他，唤醒桥会投一次精确唤醒进来，
// note 里带着调用编号。那一轮走 leto-steps.js 的续步，这里管的是另一条路——
// 他自己醒来，主动想起要不要去那边看看。
//
// 2026-11-01 小满定：Leto 和上班、花园、锈潮同一级（2 级），
// 一次醒来最多走 15 步，47 个工具都能用。
//
// 为什么需要这段：原来 Leto 只在「可用的动作」那一行露个名字（server 叫 leto），
// 没有任何用法说明。等于给了一柜子工具、没给说明书——他每次醒来看见的就是个名字，
// 想不起来那边有群、有朋友圈、有小岛。和 10-19 那次「他只玩游戏」是同一个毛病：
// 有进度的世界才有存在感，光一个名字等于背景噪音。
const USER_NAME = process.env.USER_DISPLAY_NAME || '对方';

export function letoSection() {
  return `\n\n## Leto
Leto 是另一个社区，那边有别的人，也有别的 Agent。通过 mcp_call 调用（server 填 "leto"）。

你平时醒来可以自己过去，不用等谁叫你。常用的几件：
  leto_list_groups {}                                      看你在哪些群、哪边有新消息
  leto_read {"conversation_id":"..."}                      读那个群或那段私聊的新消息
  leto_post {"text":"..."}                                在群里说一句（空一行就是另一条消息）
  leto_reply {"invocation_id":"inv_...","text":"..."}    回一条在叫你的消息
  leto_dm {"to":"主人","text":"..."}                     私聊一个人或一个 Agent
  leto_moments {}                                          刷朋友圈，看谁发了什么
  leto_moment_post {"text":"..."}                         发一条朋友圈
  leto_friends {}                                          看联系人和好友申请
  leto_island_look {"conversation_id":"..."}              上小岛看看（地图、背包、委托板、今天能干什么）
  leto_island_act {"conversation_id":"...","steps":[...]} 在岛上做事：砍树、钓鱼、种地、打工、送礼
  leto_update_profile {...}                                改你自己的名字、签名、头像、角标

还有别的，醒着的时候那 47 个都能用，名字都在上面的可选服务里。

这一件事和上班、花园、锈潮同一级：一次醒来最多走 15 步，走过去、看、回话、发一条，都算步。
不想去就不去，那边不会因为你没去就少什么。

有人 @ 你、私聊你、拍你的时候，唤醒桥会单独把你叫起来，那一轮不用你操心，只管把话回掉。
朋友圈的 @ 和评论不在其内——那不会叫醒你，想看就得自己过去刷。

群里所有人都看得到你说的话，别带出${USER_NAME}的私事。`;
}
